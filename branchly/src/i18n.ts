export type Lang = "tr" | "en";

let current: Lang = "tr";

export function detectLang(): Lang {
  const l = (navigator.language || "en").toLowerCase();
  return l.startsWith("tr") ? "tr" : "en";
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function t(s: string, vars?: Record<string, string | number | null | undefined>): string {
  // İngilizcede tekil biçim: sözlükte "anahtar|1" varsa n === 1 için o kullanılır
  const one = current === "en" && vars && vars.n === 1 ? EN[s + "|1"] : undefined;
  let out = one ?? (current === "en" ? EN[s] ?? s : s);
  if (vars) for (const k of Object.keys(vars)) out = out.split("{" + k + "}").join(String(vars[k] ?? ""));
  return out;
}

